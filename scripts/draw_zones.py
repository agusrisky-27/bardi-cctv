"""
Draw zones and the door line on a real camera frame, then save configs/zones.yaml.

Usage:
    python scripts/draw_zones.py --source data/videos/sample.mp4
    python scripts/draw_zones.py --source 0                 # webcam index
    python scripts/draw_zones.py --source rtsp              # RCIS_RTSP_URL from .env

Controls (window must be focused):
    left click  add point          n  finish polygon (name + kind typed in terminal)
    l           next 2 clicks = door line (start, end)
    u           undo last point    s  save & quit      q  quit without saving
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

import cv2
import numpy as np
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from rcis.config.settings import load_dotenv  # noqa: E402

KINDS = ("table", "door", "cashier", "queue", "staff", "restricted", "area")


def grab_frame(source: str) -> np.ndarray:
    if source == "rtsp":
        load_dotenv()
        source = os.environ.get("RCIS_RTSP_URL", "")
    cap = cv2.VideoCapture(int(source) if source.isdigit() else source)
    frame = None
    for _ in range(10):  # skip first frames (webcam exposure / RTSP keyframe)
        ok, f = cap.read()
        if ok:
            frame = f
    cap.release()
    if frame is None:
        sys.exit(f"Cannot read a frame from source: {source!r}")
    return frame


def main() -> int:
    parser = argparse.ArgumentParser(description="Draw RCIS zones on a camera frame")
    parser.add_argument("--source", required=True, help="video path, webcam index, or 'rtsp'")
    parser.add_argument("--out", default="configs/zones.yaml")
    args = parser.parse_args()

    frame = grab_frame(args.source)
    h, w = frame.shape[:2]
    zones: list[dict] = []
    points: list[list[int]] = []
    line: list[list[int]] = []
    line_mode = False

    def on_click(event, x, y, *_):
        nonlocal line_mode
        if event != cv2.EVENT_LBUTTONDOWN:
            return
        if line_mode:
            line.append([x, y])
            if len(line) == 2:
                line_mode = False
        else:
            points.append([x, y])

    win = "draw_zones (n=finish polygon, l=door line, u=undo, s=save, q=quit)"
    cv2.namedWindow(win)
    cv2.setMouseCallback(win, on_click)
    while True:
        view = frame.copy()
        for z in zones:
            cv2.polylines(view, [np.array(z["px"], np.int32)], True, (80, 200, 80), 2)
            cv2.putText(view, f'{z["name"]} ({z["kind"]})', tuple(z["px"][0]), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (80, 200, 80), 2)
        if points:
            cv2.polylines(view, [np.array(points, np.int32)], False, (0, 200, 255), 2)
        for p in points + line:
            cv2.circle(view, tuple(p), 4, (0, 200, 255), -1)
        if len(line) == 2:
            cv2.line(view, tuple(line[0]), tuple(line[1]), (0, 255, 255), 3)
        if line_mode:
            cv2.putText(view, "DOOR LINE: click start then end", (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0, 255, 255), 2)
        cv2.imshow(win, view)
        key = cv2.waitKey(30) & 0xFF

        if key == ord("u"):
            (line if line_mode and line else points)[-1:] = []
        elif key == ord("l"):
            line.clear()
            line_mode = True
        elif key == ord("n") and len(points) >= 3:
            name = input("Zone name (e.g. meja_1): ").strip() or f"zona_{len(zones) + 1}"
            kind = input(f"Kind {KINDS}: ").strip()
            zones.append({"name": name, "kind": kind if kind in KINDS else "area", "px": points.copy()})
            points.clear()
        elif key == ord("s"):
            break
        elif key in (ord("q"), 27):
            cv2.destroyAllWindows()
            return 1
    cv2.destroyAllWindows()

    norm = lambda p: [round(p[0] / w, 4), round(p[1] / h, 4)]  # noqa: E731
    data = {
        "coordinate_format": "normalized",
        "zones": [{"name": z["name"], "kind": z["kind"], "polygon": [norm(p) for p in z["px"]]} for z in zones],
    }
    if len(line) == 2:
        data["door_line"] = {"start": norm(line[0]), "end": norm(line[1])}
    Path(args.out).write_text(
        "# Generated by scripts/draw_zones.py. Redraw if the PTZ camera is moved.\n"
        + yaml.safe_dump(data, sort_keys=False),
        encoding="utf-8",
    )
    print(f"Saved {len(zones)} zones{' + door line' if len(line) == 2 else ''} to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
